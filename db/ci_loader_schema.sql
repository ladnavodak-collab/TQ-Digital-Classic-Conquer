  `portal_x` INT UNSIGNED NOT NULL DEFAULT 0,
  `portal_y` INT UNSIGNED NOT NULL DEFAULT 0,
  `reborn_map` INT UNSIGNED NOT NULL DEFAULT 0,
  `reborn_portal` INT NOT NULL DEFAULT 0,
  `light` INT UNSIGNED NOT NULL DEFAULT 0
