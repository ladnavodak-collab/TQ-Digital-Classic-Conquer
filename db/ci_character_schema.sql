-- Disposable test-only account/character fixtures, never production deployment.
-- IMPORTANT: COPS Player::SQLDATA_* uses SELECT * ordinal positions.
CREATE TABLE `account` (
  `id` INT UNSIGNED NOT NULL PRIMARY KEY,
  `name` VARCHAR(32) NOT NULL UNIQUE,
  `password` VARCHAR(255) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE `user` (
  `account_id` INT UNSIGNED NOT NULL,
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(32) NOT NULL,
  `mate` VARCHAR(32) NOT NULL DEFAULT '',
  `lookface` INT UNSIGNED NOT NULL DEFAULT 1003,
  `hair` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `money` INT UNSIGNED NOT NULL DEFAULT 0,
  `money_saved` INT UNSIGNED NOT NULL DEFAULT 0,
  `cps` INT UNSIGNED NOT NULL DEFAULT 0,
  `level` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `exp` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `force` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `dexterity` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `health` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `soul` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `add_points` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `life` SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  `mana` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `profession` TINYINT UNSIGNED NOT NULL DEFAULT 10,
  `pk` SMALLINT NOT NULL DEFAULT 0,
  `virtue` INT NOT NULL DEFAULT 0,
  `nobility` INT UNSIGNED NOT NULL DEFAULT 0,
  `metempsychosis` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `syndicate_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `record_map` INT UNSIGNED NOT NULL DEFAULT 1002,
  `record_x` SMALLINT UNSIGNED NOT NULL DEFAULT 8,
  `record_y` SMALLINT UNSIGNED NOT NULL DEFAULT 8,
  `last_login` DATETIME NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `one_character_per_account` (`account_id`),
  UNIQUE KEY `unique_character_name` (`name`),
  CONSTRAINT `test_classic_no_cps` CHECK (`cps` = 0),
  CONSTRAINT `test_classic_single_rebirth` CHECK (`metempsychosis` <= 1)
) ENGINE=InnoDB;
CREATE TABLE `item` (`id` INT UNSIGNED NOT NULL PRIMARY KEY,`player_id` INT UNSIGNED NOT NULL);
CREATE TABLE `weaponskill` (`id` INT UNSIGNED NOT NULL PRIMARY KEY,`owner_id` INT UNSIGNED NOT NULL);
CREATE TABLE `magic` (`id` INT UNSIGNED NOT NULL PRIMARY KEY,`owner_id` INT UNSIGNED NOT NULL);
